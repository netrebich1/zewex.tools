/** Инструкция «Подбора ключей»: установка и обновление расширения, как читать цифры. */
export default async function GuidePage({ searchParams }: { searchParams: Promise<SearchParams> }) {
  await requireKeywords();
  const tab = sp(await searchParams, "tab") === "metrics" ? "metrics" : "ext";
  const version = await extensionVersion();
  return (
    <>
      <PageHeader title="Инструкция" subtitle="Как поставить расширение для сбора и как читать цифры инструмента." />
      <KeywordsNav />
      <div className="mb-4 inline-flex gap-1 rounded-xl bg-ink/5 p-1">
        {([["ext", "Расширение"], ["metrics", "Как читать цифры"]] as const).map(([k, l]) => (
          <Link key={k} href={k === "ext" ? "/pinterest/keywords/guide" : "/pinterest/keywords/guide?tab=metrics"} className={`rounded-lg px-3 py-1.5 text-[13px] font-semibold transition ${tab === k ? "bg-surface text-ink shadow-[var(--shadow-card)]" : "text-muted hover:text-ink"}`}>{l}</Link>
        ))}
      </div>
      {tab === "ext" ? <ExtensionGuide version={version} /> : <MetricsGuide />}
    </>
  );
}
