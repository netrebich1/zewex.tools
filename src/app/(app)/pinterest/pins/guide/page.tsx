async function shotUrl(file: string): Promise<string | null> {
  const rel = `pins/guide/${file}.jpg`;
  try { const s = await stat(absPath(rel)); return `${publicUrl(rel)}?v=${Math.round(s.mtimeMs)}`; } catch { return null; }
}

export default async function PinsGuidePage({ searchParams }: { searchParams: Promise<SearchParams> }) {
  await requireUser();
  const tab = sp(await searchParams, "tab") === "cooking" ? "cooking" : "main";
  const steps = tab === "cooking" ? COOKING : MAIN;
  const urls = new Map<string, string | null>();
  await Promise.all(steps.flatMap((s) => s.shots).map(async (sh) => urls.set(sh.file, await shotUrl(sh.file))));
  const pill = (k: string, label: string) => <Link href={`/pinterest/pins/guide${k === "main" ? "" : `?tab=${k}`}`} className={`badge px-3 py-1 max-sm:!py-1.5 max-sm:min-h-8 ${tab === k ? "bg-ink text-bg" : "bg-ink/5 hover:bg-ink/10"}`}>{label}</Link>;

  return (
    <>
      <PageHeader title="Инструкция" subtitle="Вся работа с пинами по шагам: от настройки сайта до файла для Pinterest. Оранжевые цифры на снимках соответствуют пунктам рядом. Нажмите на снимок, чтобы увеличить." />
      <div className="space-y-4">
        <div className="flex flex-wrap gap-2">{pill("main", "Основная инструкция")}{pill("cooking", "Кулинария: отличия")}</div>
        <Card>
          <ol className="grid gap-x-6 gap-y-1 text-[14px] sm:grid-cols-2 lg:grid-cols-3">
            {steps.map((s, i) => <li key={s.id}><a href={`#${s.id}`} className="hover:underline"><span className="text-muted">{i + 1}.</span> {s.title}</a></li>)}
          </ol>
        </Card>

        {steps.map((s, i) => (
          <section key={s.id} id={s.id} className="card p-4 sm:p-5 scroll-mt-20 space-y-4">
            <div className="flex flex-wrap items-start gap-3">
              <span className="inline-flex h-8 w-8 shrink-0 items-center justify-center rounded-full bg-ink text-bg text-[14px] font-bold">{i + 1}</span>
              <div className="min-w-0 flex-1"><h2 className="h2">{s.title}</h2><p className="help">{s.where}</p></div>
              {s.href && <Link href={s.href} className="btn-ghost btn-sm">Открыть этот экран</Link>}
            </div>
            {s.intro && <p className="text-[14px]">{s.intro}</p>}
            {s.shots.map((sh) => {
              const url = urls.get(sh.file);
              const list = sh.marks?.length ? (
                <ol className="space-y-2 text-[14px]">
                  {sh.marks.map((m, k) => (
                    <li key={k} className="flex gap-2.5"><span className="mt-0.5 inline-flex h-5 w-5 shrink-0 items-center justify-center rounded-full bg-[#ffab1a] text-[12px] font-bold text-[#111]">{k + 1}</span><span>{m}</span></li>
                  ))}
                </ol>
              ) : null;
              return (
                <div key={sh.file} className={sh.wide || !list ? "space-y-3" : "grid gap-4 lg:grid-cols-[minmax(0,340px)_1fr] lg:items-start"}>
                  {(list || (sh.caption && !url)) && <div className="space-y-2">{sh.caption && list && <div className="text-[13px] font-semibold">{sh.caption}</div>}{list}</div>}
                  {url && <GuideShot src={url} alt={sh.caption ?? s.title} caption={list ? undefined : sh.caption} />}
                </div>
              );
            })}
            {s.blocks && (
              <div className="grid gap-3 lg:grid-cols-2">
                {s.blocks.map((b) => (
                  <div key={b.title} className="rounded-xl border border-line p-3">
                    <div className="mb-1.5 text-[13px] font-semibold">{b.title}</div>
                    <ul className="space-y-1.5 text-[14px] list-disc pl-5">{b.items.map((it, k) => <li key={k}>{it}</li>)}</ul>
                  </div>
                ))}
              </div>
            )}
            {s.tips && (
              <ul className="space-y-1.5 rounded-lg bg-ink/5 px-4 py-3 text-[13.5px] list-disc pl-8">
                {s.tips.map((t, k) => <li key={k}>{t}</li>)}
              </ul>
            )}
          </section>
        ))}

        {tab === "main" && (
          <Card title="Если что-то пошло не так">
            <dl className="space-y-3 text-[14px]">
              {PROBLEMS.map(([q, a]) => <div key={q}><dt className="font-medium">{q}</dt><dd className="text-muted">{a}</dd></div>)}
            </dl>
          </Card>
        )}
      </div>
    </>
  );
}
