def build():
    out, num = [], 9101
    for b in BASES:
        for k, pal in enumerate(b["palettes"], start=1):
            label, color = PALETTES[pal]
            out.append({
                "id": f"{b['key']}-{k}",
                "num": num,
                "name": f"{b['name']} /{k}",
                "category": "newyear",
                "type": b["type"],
                "variantOf": b["key"],
                "variantLabel": label,
                "baseName": b["name"],
                "niches": ["decor", "interior"],
                "concept": b["concept"],
                "layout": b["layout"],
                "typography": b["typography"],
                "colorLogic": color,
                "decorative": b["decorative"],
                "avoid": COMMON_AVOID,
                "gold": b["gold"],
            })
            num += 1
    return out


def main():
    d = json.load(io.open(PATH, encoding="utf-8"))
    new = build()
    ids = {s["id"] for s in new}
    d["styles"] = [s for s in d["styles"] if s["id"] not in ids] + new
    for c in d["categories"]:
        if c["id"] == "newyear":
            c["note"] = "Новогодние направления: универсальные для моды и красоты + отдельная линия для декора и дизайна интерьера (фильтр «Декор»)."
    io.open(PATH, "w", encoding="utf-8").write(json.dumps(d, ensure_ascii=False, indent=2) + "\n")
    print(f"added {len(new)} styles")


if __name__ == "__main__":
    main()
