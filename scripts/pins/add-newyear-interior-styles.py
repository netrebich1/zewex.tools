def build():
    out, num = [], 9201
    for b in BASES:
        for k, label, mood in VARIANTS:
            out.append({
                "id": f"{b['key']}-{k}",
                "num": num,
                "name": f"{b['name']} /{k}",
                "category": CATEGORY["id"],
                "type": b["type"],
                "variantOf": b["key"],
                "variantLabel": label,
                "baseName": b["name"],
                "universal": True,
                "niches": ["decor", "interior"],
                "concept": b["concept"],
                "layout": b["layout"],
                "typography": b["typography"],
                "colorLogic": mood + COLOR_RULE + CONTENT_RULE,
                "decorative": b["decorative"],
                "avoid": COMMON_AVOID,
                "gold": b["gold"],
            })
            num += 1
    return out


def main():
    d = json.load(io.open(PATH, encoding="utf-8"))
    new = build()
    ids = {s["id"] for s in new}
    d["styles"] = [s for s in d["styles"] if s["id"] not in ids] + new
    cats = [c for c in d["categories"] if c["id"] != CATEGORY["id"]]
    at = next((i + 1 for i, c in enumerate(cats) if c["id"] == "newyear"), len(cats))
    d["categories"] = cats[:at] + [CATEGORY] + cats[at:]
    io.open(PATH, "w", encoding="utf-8", newline="\n").write(json.dumps(d, ensure_ascii=False, indent=2) + "\n")
    print(f"added {len(new)} styles")


if __name__ == "__main__":
    main()
